unsigned int anchor_impact_visual_material_id(unsigned int pointer) {
    unsigned int i; pointer &= ~0x60000000u;
    if (!pointer) return 0;
    for (i = 1; i < sizeof(materials)/sizeof(materials[0]); ++i)
        if (pointer == (unsigned int)(unsigned long)materials[i]) return i;
    return 0xffffffffu;
}
